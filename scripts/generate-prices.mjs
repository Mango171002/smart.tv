// Single source of truth for the PLANNED price list (USD, before taxes).
// Generates src/config/price-tables.json (used by the site) and supabase/seed.sql.
// Prices stay `illustrative` in the database until approved for sale.
// Run: npm run prices
import { writeFileSync } from 'node:fs';

export const TERMS = ['12m', '24m', '36m', 'lifetime'];
const TERM_MONTHS = { '12m': 12, '24m': 24, '36m': 36, lifetime: null };
export const TIERS = [
  { code: 'starter', sort: 1, quality: 'hd' },
  { code: 'plus', sort: 2, quality: 'uhd' },
  { code: 'ultra', sort: 3, quality: 'uhd' },
];
export const STREAMS = [1, 2, 3, 4];
// Extra simultaneous screen, per term (USD). Keeps every price ending in 9 or 5.
const EXTRA_STREAM_USD = { '12m': 10, '24m': 20, '36m': 30, lifetime: 50 };
// Owner's 12-month prices (49 / 59 / 69 USD, 1 screen) + charm prices for longer terms.
const PRICES_USD = {
  starter: { '12m': 49, '24m': 79, '36m': 99, lifetime: 149 },
  plus: { '12m': 59, '24m': 95, '36m': 119, lifetime: 179 },
  ultra: { '12m': 69, '24m': 109, '36m': 139, lifetime: 199 },
};

const price = (tier, term, streams) => PRICES_USD[tier][term] + (streams - 1) * EXTRA_STREAM_USD[term];

const json = {
  _comment: 'GENERATED by scripts/generate-prices.mjs — planned prices (USD, before taxes), not yet approved for sale.',
  currency: 'USD',
  market: 'US',
  terms: TERMS,
  termMonths: TERM_MONTHS,
  streams: STREAMS,
  extraStreamMinor: Object.fromEntries(TERMS.map((t) => [t, EXTRA_STREAM_USD[t] * 100])),
  tiers: TIERS,
  // prices[tier][term][streams] in cents
  prices: Object.fromEntries(
    TIERS.map((t) => [
      t.code,
      Object.fromEntries(TERMS.map((term) => [term, Object.fromEntries(STREAMS.map((n) => [n, price(t.code, term, n) * 100]))])),
    ]),
  ),
};
writeFileSync(new URL('../src/config/price-tables.json', import.meta.url), JSON.stringify(json, null, 2) + '\n');

const combos = TIERS.flatMap((t) => TERMS.flatMap((term) => STREAMS.map((n) => ({ tier: t.code, term, n }))));
const rows = combos.map(({ tier, term, n }) => `  ('${tier}', '${term}', ${TERM_MONTHS[term] ?? 'null'}, ${n})`);
const sql = `-- GENERATED by scripts/generate-prices.mjs — do not edit by hand.
-- Planned offer: 3 tiers x 4 terms x 1-4 streams, prices in USD (market US), status
-- 'illustrative' until approved for sale. Idempotent, never deletes data.

insert into public.markets (code, name, currency, default_locale, licensed, sales_enabled, tax_inclusive_pricing)
values
  ('US', 'United States', 'USD', 'en', false, false, false),
  ('CA', 'Canada', 'CAD', 'en', false, false, false),
  ('EU', 'Europe', 'EUR', 'en', false, false, true)
on conflict (code) do nothing;

insert into public.plan_tiers (code, sort_order, max_quality)
values
${TIERS.map((t) => `  ('${t.code}', ${t.sort}, '${t.quality}')`).join(',\n')}
on conflict (code) do nothing;

insert into public.plans (tier_code, term, duration_months, streams)
select v.tier_code, v.term, v.duration_months, v.streams
from (values
${rows.join(',\n')}
) as v (tier_code, term, duration_months, streams)
on conflict (tier_code, term, streams) where tier_code is not null do nothing;

insert into public.prices (market_code, plan_id, currency, amount_minor, status)
select 'US', p.id, 'USD', v.amount_minor, 'illustrative'
from (values
${combos.map(({ tier, term, n }) => `  ('${tier}', '${term}', ${n}, ${price(tier, term, n) * 100})`).join(',\n')}
) as v (tier_code, term, streams, amount_minor)
join public.plans p on p.tier_code = v.tier_code and p.term = v.term and p.streams = v.streams
where not exists (
  select 1 from public.prices x
   where x.market_code = 'US' and x.plan_id = p.id and x.valid_to is null and x.status <> 'retired'
);
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('Generated', rows.length, 'planned prices');
