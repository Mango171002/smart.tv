// Generates the ILLUSTRATIVE prototype price tables (one table per market, in
// minor units) and the matching Supabase seed file.
//
// These values reproduce the approved prototype display exactly. They are NOT
// commercial prices: every row is tagged `illustrative`. Real prices must be
// entered per market as `approved` rows after business sign-off — never derived
// by currency conversion.
import { writeFileSync } from 'node:fs';

const durations = [1, 3, 6, 12];
const streams = [1, 2, 3, 4];
const prototypeBaseUsd = { 1: 14, 3: 34, 6: 54, 12: 79 };
// Prototype-only factors, frozen here once to build static per-market tables.
const prototypeFactor = { US: 1, CA: 1.32, EU: 0.92 };
const currency = { US: 'USD', CA: 'CAD', EU: 'EUR' };

const tables = {};
for (const market of Object.keys(prototypeFactor)) {
  tables[market] = { currency: currency[market], status: 'illustrative', prices: {} };
  for (const d of durations) {
    for (const s of streams) {
      const major = prototypeBaseUsd[d] * (1 + (s - 1) * 0.55) * prototypeFactor[market];
      tables[market].prices[`${d}x${s}`] = Math.round(Number(major.toFixed(2)) * 100);
    }
  }
}

writeFileSync(
  new URL('../src/config/prototype-price-tables.json', import.meta.url),
  JSON.stringify({ _comment: 'GENERATED by scripts/generate-prototype-prices.mjs — illustrative only, not commercial prices.', durations, streams, tables }, null, 2) + '\n',
);

const rows = [];
for (const [market, t] of Object.entries(tables)) {
  for (const [key, amount] of Object.entries(t.prices)) {
    const [d, s] = key.split('x');
    rows.push(`  ('${market}', ${d}, ${s}, '${t.currency}', ${amount})`);
  }
}

const sql = `-- GENERATED by scripts/generate-prototype-prices.mjs — do not edit by hand.
-- Development seed: ILLUSTRATIVE data only. Markets are NOT licensed and sales are
-- disabled. Idempotent: safe to run several times, never deletes data.

insert into public.markets (code, name, currency, default_locale, licensed, sales_enabled, tax_inclusive_pricing)
values
  ('US', 'United States', 'USD', 'en', false, false, false),
  ('CA', 'Canada', 'CAD', 'en', false, false, false),
  ('EU', 'Europe', 'EUR', 'en', false, false, true)
on conflict (code) do nothing;

insert into public.plans (duration_months, streams)
select d, s from unnest(array[${durations.join(', ')}]) d cross join unnest(array[${streams.join(', ')}]) s
on conflict (duration_months, streams) do nothing;

insert into public.prices (market_code, plan_id, currency, amount_minor, status)
select v.market_code, p.id, v.currency, v.amount_minor, 'illustrative'
from (values
${rows.join(',\n')}
) as v (market_code, duration_months, streams, currency, amount_minor)
join public.plans p on p.duration_months = v.duration_months and p.streams = v.streams
where not exists (
  select 1 from public.prices x
   where x.market_code = v.market_code and x.plan_id = p.id
     and x.valid_to is null and x.status <> 'retired'
);
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('Generated', rows.length, 'illustrative prices');
