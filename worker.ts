/**
 * Cloudflare Worker entry: the OpenNext worker (site) + a scheduled handler.
 * Every hour the cron trigger calls the internal route that sends the Trustpilot review
 * invitations that are due (3 days after « Converti »). The route checks a secret derived
 * from SUPABASE_SECRET_KEY (same derivation as src/lib/cron.ts).
 *
 * Private preview (SITE_MODE = "preview", separate Worker « sygma-tv-preview », wrangler.preview.jsonc):
 * - every request needs the preview password (HTTP Basic, secret PREVIEW_PASSWORD); without the secret
 *   the preview stays locked (fail-closed);
 * - every response carries X-Robots-Tag: noindex, nofollow;
 * - every /api/* route is refused (no order, trial, support request, quote, webhook or cron), whatever
 *   the browser sends — only /api/health answers;
 * - no scheduled work.
 * The production Worker has no SITE_MODE: its behaviour is unchanged.
 */
// @ts-expect-error -- generated by `opennextjs-cloudflare build`
import { default as handler } from './.open-next/worker.js';
import { previewFetch } from './src/lib/preview-gate';

interface Env {
  SUPABASE_SECRET_KEY?: string;
  SITE_MODE?: string;
  PREVIEW_PASSWORD?: string;
  [key: string]: unknown;
}
type Ctx = { waitUntil(p: Promise<unknown>): void };

async function cronSecret(key: string): Promise<string> {
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(`${key}:sygma-cron`));
  return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, '0')).join('').slice(0, 48);
}

const worker = {
  fetch(req: Request, env: Env, ctx: Ctx) {
    if (env.SITE_MODE === 'preview') return previewFetch(req, env, ctx, handler.fetch);
    return handler.fetch(req, env, ctx);
  },
  async scheduled(_event: unknown, env: Env, ctx: Ctx) {
    if (env.SITE_MODE === 'preview') return;
    if (!env.SUPABASE_SECRET_KEY) return;
    const secret = await cronSecret(env.SUPABASE_SECRET_KEY);
    const req = new Request('https://sygmatv.com/api/cron/review-invites', { method: 'POST', headers: { 'x-cron-secret': secret } });
    ctx.waitUntil(
      Promise.resolve(handler.fetch(req, env, ctx))
        .then(async (res: Response) => console.log('[cron] review-invites', res.status, await res.text()))
        .catch((e: unknown) => console.warn('[cron] review-invites', (e as Error).message)),
    );
  },
};

export default worker;

